# Writes files the core carries into a C source, for the static Makefile build. POSIX sh,
# od and awk only. The CMake build does the same with libretro/embed_host.cmake and
# cmake/EmbedResources.cmake, since the MSVC Windows build has no sh: keep them in step.
#
#   embed.sh host <out.c> <executable>
#       the launcher (libretro/host_main.c), as g_libretro_host
#   embed.sh resources <out.c> <root> <path>...
#       files by their path from <root>, as g_embedded_resources
#       (src/common/embedded_resources.h)
set -e

bytes() {
	od -An -v -t x1 "$1" | awk '
	{
		for (i = 1; i <= NF; i++) {
			line = line "0x" $i ","
			if (++n == 24) { print line; line = ""; n = 0 }
		}
	}
	END { if (line != "") print line }'
}

size() {
	wc -c < "$1" | tr -d ' '
}

mode="$1"
out="$2"
shift 2
# written aside and moved in place, so a failed run leaves no half file behind
tmp="$out.tmp"

case "$mode" in
host)
	{
		echo "/* Generated by libretro/embed.sh from the launcher's executable. */"
		echo "const unsigned char g_libretro_host[] = {"
		bytes "$1"
		echo "};"
		echo "const unsigned long g_libretro_host_size = $(size "$1");"
	} > "$tmp"
	;;
resources)
	root="$1"
	shift
	{
		echo "/* Generated by libretro/embed.sh. */"
		echo "struct EmbeddedResource {"
		echo "    const char *path;"
		echo "    const unsigned char *data;"
		echo "    unsigned long size;"
		echo "};"
		index=0
		for path in "$@"; do
			echo "static const unsigned char resource_$index[] = {"
			bytes "$root/$path"
			echo "};"
			index=$((index + 1))
		done
		echo "const struct EmbeddedResource g_embedded_resources[] = {"
		index=0
		for path in "$@"; do
			echo "    {\"$path\", resource_$index, $(size "$root/$path")},"
			index=$((index + 1))
		done
		echo "};"
		echo "const unsigned long g_embedded_resource_count = $index;"
	} > "$tmp"
	;;
*)
	echo "usage: $0 host <out.c> <executable> | resources <out.c> <root> <path>..." >&2
	exit 1
	;;
esac
mv -f "$tmp" "$out"
